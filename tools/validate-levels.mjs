// Validates every level (and a range of daily puzzles):
//   - the solution produces the target melody
//   - the start position is not already solved
//   - the stored par path is legal and solves the level
// Then runs a bounded breadth-first search to find the true optimal number
// of moves where feasible, and writes src/levels/par-table.js.
//
// Usage: node tools/validate-levels.mjs [--no-search] [--budget=N]

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { getLevel, getDailyLevel, verifyLevel, TOTAL_LEVELS } from '../src/levels/index.js';
import { applyMove, evaluate, occupancy, resolveDrop, tileSignature } from '../src/game/model.js';

const args = process.argv.slice(2);
const noSearch = args.includes('--no-search');
const budgetArg = args.find((a) => a.startsWith('--budget='));
const BUDGET = budgetArg ? Number(budgetArg.split('=')[1]) : 400000;

function stateKey(L, S) {
  const occ = occupancy(L, S);
  let k = '';
  for (let c = 0; c < occ.length; c++) {
    const t = occ[c];
    if (t < 0) k += '.';
    else k += tileSignature(L.tiles[t]) + (L.tiles[t].kind === 'rotor' ? S.rot[t] : '');
    k += '|';
  }
  return k;
}

function neighbors(L, S) {
  const out = [];
  for (let t = 0; t < L.tiles.length; t++) {
    const tile = L.tiles[t];
    if (tile.kind === 'rotor') out.push(applyMove(L, S, { type: 'rotate', tile: t }).state);
    if (tile.locked) continue;
    for (let c = 0; c < L.cells.length; c++) {
      if (L.cells[c].void || c === S.pos[t]) continue;
      if (!resolveDrop(L, S, t, c).ok) continue;
      out.push(applyMove(L, S, { type: 'drop', tile: t, cell: c }).state);
    }
  }
  return out;
}

/** Returns optimal depth if found below `limit`, `limit` if proven optimal, or null if budget ran out. */
function optimalDepth(L, limit) {
  let frontier = [L.start];
  const seen = new Set([stateKey(L, L.start)]);
  let nodes = 0;
  for (let depth = 1; depth < limit; depth++) {
    const next = [];
    for (const s of frontier) {
      for (const n of neighbors(L, s)) {
        nodes++;
        if (nodes > BUDGET) return null;
        const key = stateKey(L, n);
        if (seen.has(key)) continue;
        seen.add(key);
        if (evaluate(L, n).solved) return depth;
        next.push(n);
      }
    }
    frontier = next;
  }
  return limit;
}

let failures = 0;
const table = {};
const summary = [];
const t0 = Date.now();

for (let id = 1; id <= TOTAL_LEVELS; id++) {
  let L;
  try {
    L = getLevel(id);
  } catch (e) {
    console.error(`Level ${id}: build failed — ${e.message}`);
    failures++;
    continue;
  }
  const errors = verifyLevel(L);
  if (errors.length) {
    failures++;
    console.error(`Level ${id}: ${errors.join('; ')}`);
  }
  let par = L.path.length;
  let proven = false;
  if (!noSearch) {
    const opt = optimalDepth(L, par);
    if (opt !== null) {
      proven = true;
      if (opt < par) par = opt;
    }
  }
  table[id] = { par, fp: L.fingerprint, proven };
  summary.push(
    `${String(id).padStart(3)} ${L.w}x${L.h} tiles:${String(L.tiles.length).padStart(2)} notes:${String(L.target.length).padStart(2)} par:${par}${proven ? '*' : ' '} [${L.mechanics.join(',')}]`,
  );
}

// Daily puzzles for the next ~2 years.
const base = new Date(2025, 0, 1);
let dailyOk = 0;
for (let i = 0; i < 800; i++) {
  const d = new Date(base.getFullYear(), base.getMonth(), base.getDate() + i);
  const key = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  try {
    const L = getDailyLevel(key);
    const errors = verifyLevel(L);
    if (errors.length) {
      failures++;
      console.error(`Daily ${key}: ${errors.join('; ')}`);
    } else dailyOk++;
  } catch (e) {
    failures++;
    console.error(`Daily ${key}: ${e.message}`);
  }
}

console.log(summary.join('\n'));
console.log(`\nDaily puzzles verified: ${dailyOk}/800`);
console.log(`Checked ${TOTAL_LEVELS} levels in ${((Date.now() - t0) / 1000).toFixed(1)}s — ${failures} failure(s).`);
console.log('par* = proven optimal by exhaustive search');

if (!noSearch) {
  const here = dirname(fileURLToPath(import.meta.url));
  const out = join(here, '..', 'src', 'levels', 'par-table.js');
  const body = Object.entries(table)
    .map(([id, v]) => `  ${id}: { par: ${v.par}, fp: '${v.fp}' },`)
    .join('\n');
  writeFileSync(
    out,
    `// Generated by tools/validate-levels.mjs — optimal move counts found by search.\n// Entries are ignored automatically if a level changes (fingerprint mismatch).\nexport const PAR_TABLE = {\n${body}\n};\n`,
  );
  console.log(`Wrote ${out}`);
}

process.exit(failures ? 1 : 0);
